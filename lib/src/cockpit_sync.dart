/// `remembox cockpit-sync` (0.5.0): renders the live threads into a
/// generated section of the operator's cockpit file (a Markdown overview
/// of open topics) and compares the hand-written lines of that file with
/// the threads.
///
/// A CLI subcommand of the server binary, not an MCP tool: the server gets
/// no file-writing tool – agents call `thread_update`, and this
/// short-lived process writes the file. It reads the store through ONE
/// gated [StoreGate] lending (`store.lock`, like any gated peer – never a
/// second open Store next to a lending), with no embedder and no
/// [MemoryService]: [readThreadRows] is the shared read projection.
///
/// File safety (amendment A5): the cockpit is rewritten IN PLACE (same
/// inode – mode and extended attributes stay), only when the generated
/// section changed (the timestamp line does not count), after a backup of
/// the previous content (`cockpit.bak` next to the compare log, never next
/// to the cockpit), and only if the file is still exactly what was read
/// (sha256 + mtime re-checked immediately before the write – otherwise
/// exit 3, nothing written). A section from a truncated read of the live
/// threads is never written. The markers must appear exactly
/// once each, start before end; both missing appends the section; any
/// other shape refuses to write (exit 4).
///
/// The parser ([parseCockpit]) is shared by the comparison and by
/// `--parse-only` (JSON on stdout, no store access). The comparison is a
/// learning signal, not an error: it is appended as one JSON line to the
/// compare log (`OBX_MEMORY_COCKPIT_LOG`, default
/// `~/Library/Logs/remembox/cockpit-compare.log` on macOS,
/// `~/.local/state/remembox/cockpit-compare.log` elsewhere – never inside
/// the store directory), only when its content hash changed since the last
/// line.
