/// The compare log is rotated (renamed to `.1`, replacing an older one)
/// once it exceeds this size.
const int cockpitCompareLogMaxBytes = 1024 * 1024;

/// `OBX_MEMORY_COCKPIT_LOG`, or the default: on macOS
/// `~/Library/Logs/remembox/cockpit-compare.log`, elsewhere
/// `${XDG_STATE_HOME:-~/.local/state}/remembox/cockpit-compare.log`.
///
/// `tool/hooks/cockpit-sync-hook.sh` applies the same rule (`uname -s` =
/// Darwin) for its own failure lines, so hook and command log to one file.
/// [operatingSystem] is `Platform.operatingSystem` by default; a seam for
/// tests.
String cockpitCompareLogPath(
  Map<String, String> env, {
  String? operatingSystem,
}) {
  final explicit = env['OBX_MEMORY_COCKPIT_LOG'] ?? '';
  if (explicit.isNotEmpty) return explicit;
  final home = env['HOME'] ?? '';
  if ((operatingSystem ?? Platform.operatingSystem) == 'macos') {
    return p.join(home, 'Library', 'Logs', 'remembox', 'cockpit-compare.log');
  }
  final xdgState = env['XDG_STATE_HOME'] ?? '';
  final stateDir = xdgState.isNotEmpty
      ? xdgState
      : p.join(home, '.local', 'state');
  return p.join(stateDir, 'remembox', 'cockpit-compare.log');
}

/// The `hash` of the last line of the compare log, or null (no file, no
/// line, or a failure line without a hash). Reads only the file's tail.
String? _lastLoggedHash(File file, LogSink log) {
  if (!file.existsSync()) return null;
  final raf = file.openSync();
  final String tail;
  try {
    final length = raf.lengthSync();
    final start = length > 65536 ? length - 65536 : 0;
    raf.setPositionSync(start);
    tail = utf8.decode(raf.readSync(length - start), allowMalformed: true);
  } finally {
    raf.closeSync();
  }
  final lines = tail.split('\n').where((l) => l.trim().isNotEmpty).toList();
  if (lines.isEmpty) return null;
  try {
    final last = jsonDecode(lines.last);
    return last is Map ? last['hash'] as String? : null;
  } on FormatException catch (err) {
    log(
      '[cockpit] WARN: the last line of ${file.path} is not JSON '
      '(${err.message}) – appending a new line',
    );
    return null;
  }
}

/// Appends [line] (one JSON object) to the compare log, creating it (mode
/// 600 – the lines carry cockpit titles) and its directory when needed,
/// and rotating it to `.1` first when it is over
/// [cockpitCompareLogMaxBytes] (logged). A log that already exists with
/// group or other permissions (created by an older build, or by the hook
/// script's own failure lines before the hook created it with 600) is
/// tightened to 600 too, and that is logged.
void _appendCompareLog(String path, Map<String, Object?> line, LogSink log) {
  var file = File(path);
  if (file.existsSync() && file.lengthSync() > cockpitCompareLogMaxBytes) {
    file.renameSync('$path.1');
    log(
      '[cockpit] the compare log $path exceeded '
      '$cockpitCompareLogMaxBytes bytes – rotated to $path.1',
    );
    file = File(path);
  }
  final created = !file.existsSync();
  if (created) file.parent.createSync(recursive: true);
  file.writeAsStringSync('${jsonEncode(line)}\n', mode: FileMode.append);
  if (created) {
    tightenPermissions(path, '600', log: log);
  } else if (!Platform.isWindows && file.statSync().mode & 0x3F != 0) {
    final was = (file.statSync().mode & 0x1FF).toRadixString(8);
    log(
      '[cockpit] the compare log $path had mode $was – tightening to 600 '
      '(it carries cockpit titles)',
    );
    tightenPermissions(path, '600', log: log);
  }
}

/// Appends a failure line (no hash, so the next successful run always
/// writes); a failure to log is itself logged, never thrown.
void _logFailure(
  String path,
  String cockpit,
  String error,
  LogSink log, {
  Map<String, Object?> extra = const {},
}) {
  try {
    _appendCompareLog(path, {
      'at': DateTime.now().toUtc().toIso8601String(),
      'cockpit': cockpit,
      'error': error,
      ...extra,
    }, log);
  } on FileSystemException catch (err) {
    log('[cockpit] WARN: could not write the compare log $path: $err');
  }
}

