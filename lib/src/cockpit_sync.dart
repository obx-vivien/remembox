/// The generated section's markers – each on its own line.
const String cockpitStartMarker = '<!-- remembox:threads:start -->';
const String cockpitEndMarker = '<!-- remembox:threads:end -->';

/// The first words of the generated timestamp line – excluded when
/// deciding whether the section changed.
const String _generatedLinePrefix = '_Generated by `remembox cockpit-sync`';

/// Exit codes of `remembox cockpit-sync`.
abstract final class CockpitExit {
  static const ok = 0;

  /// I/O or store error (also: no store at the configured directory).
  static const error = 1;

  /// Usage error (unknown option, no cockpit file given).
  static const usage = 2;

  /// The cockpit changed between reading and writing – nothing written.
  static const changedDuringSync = 3;

  /// The markers are not exactly one start before one end – nothing
  /// written.
  static const badMarkers = 4;
}

/// The state symbols a hand-written cockpit line can carry (a subset of
/// [ThreadStates.symbols]: backlog and dropped have no hand-line form).
const List<String> cockpitLineSymbols = ['▶', '⏳', '⏸', '❓', '✅'];

/// Cap for every title (Unicode code points, not UTF-16 units): titles are
/// match keys, so they stay short – the bold text up to its first separator.
const int cockpitTitleMaxLen = 80;

/// A bold label ending with `:` that has more words than this is taken
/// alone; a shorter one (`Open:`) is completed with the text after it.
const int _shortLabelMaxWords = 3;

final Map<String, String> _stateBySymbol = {
  for (final e in ThreadStates.symbols.entries)
    if (cockpitLineSymbols.contains(e.value)) e.value: e.key,
};

/// One hand-written thread line of the cockpit.
class CockpitLine {
  /// 1-based line number in the file.
  final int lineNo;

  /// The headings above the line, outermost first (verbatim).
  final List<String> sectionPath;
  final String symbol;

  /// [symbol] as a [ThreadStates] value.
  final String state;
  final String title;

  /// `#123` references in the line (entry ids by convention).
  final List<int> entryRefs;

  /// The title was cut to its cap (marked with `…`).
  final bool titleTruncated;
  final String raw;

  const CockpitLine({
    required this.lineNo,
    required this.sectionPath,
    required this.symbol,
    required this.state,
    required this.title,
    required this.entryRefs,
    required this.titleTruncated,
    required this.raw,
  });

  /// [ScopeKey] of [title] – how a line is matched to a thread.
  String get titleKey => ScopeKey.of(title);

  Map<String, Object?> toJson() => {
    'lineNo': lineNo,
    'sectionPath': sectionPath,
    'symbol': symbol,
    'state': state,
    'title': title,
    'entryRefs': entryRefs,
    if (titleTruncated) 'titleTruncated': true,
  };
}

/// What [parseCockpit] found.
class CockpitParse {
  final List<CockpitLine> lines;

  /// Line numbers of top-level lines that start with a state symbol but
  /// match no thread-line pattern.
  final List<int> unparsed;

  /// Skipped lines per reason: `detail` (`·`), `warning` (`⚠`),
  /// `numbered`, `table`, `struck`, `archive`, `nested` (indented),
  /// `generated` (between the markers).
  final Map<String, int> skipped;

  const CockpitParse(this.lines, this.unparsed, this.skipped);

  Map<String, Object?> toJson() => {
    'parsed': lines.length,
    'unparsed': unparsed.length,
    'unparsedLines': unparsed,
    'skipped': skipped,
    'lines': [for (final l in lines) l.toJson()],
  };
}

final RegExp _heading = RegExp(r'^(#{1,6})\s+(.*)$');
final RegExp _listMarker = RegExp(r'^[-*+]\s+');
final RegExp _numbered = RegExp(r'^\d+[.)]\s');
final RegExp _archiveDate = RegExp(
  r'^(?:\*\*\d{1,2}\.\d{1,2}\.(?:\d{2,4})?\*\*|\d{4}-\d{2}-\d{2}\b)',
);
final String _sym = '(${cockpitLineSymbols.join('|')})';
final RegExp _symbolAtStart = RegExp('^$_sym');
final RegExp _symbolStart = RegExp('^(?:\\*\\*\\s*)?$_sym');
final RegExp _entryRef = RegExp(r'#(\d{1,6})(?!\d)');
final RegExp _separator = RegExp(r' — | – | · |\. ');

/// Removes bold/strike/code markers and collapses whitespace.
String _cleanTitle(String s) => s
    .replaceAll('**', '')
    .replaceAll('~~', '')
    .replaceAll('`', '')
    .replaceAll(RegExp(r'\s+'), ' ')
    .trim();

/// [text] up to its first separator (` — `, ` – `, ` · `, `. `).
String _cutAtSeparator(String text) {
  final cut = _separator.firstMatch(text);
  return cut == null ? text : text.substring(0, cut.start);
}

/// The text after a symbol or label up to the first separator, without
/// leading separators.
String _firstSegment(String rest) => _cleanTitle(
  _cutAtSeparator(rest.replaceFirst(RegExp(r'^[\s—–·:-]+'), '')),
);

/// Final shape of every title: no trailing full stop, at most
/// [cockpitTitleMaxLen] code points (never splitting a surrogate pair),
/// cut ones end with `…`.
({String title, bool truncated}) _capTitle(String title) {
  final t = title.replaceFirst(RegExp(r'\.+$'), '').trim();
  final runes = t.runes.toList();
  if (runes.length <= cockpitTitleMaxLen) return (title: t, truncated: false);
  return (
    title:
        '${String.fromCharCodes(runes.take(cockpitTitleMaxLen - 1)).trimRight()}…',
    truncated: true,
  );
}

/// The title of a line from its bold part and the text after it – a
/// stable match key, not the whole sentence: the bold text up to its first
/// separator; an empty bold → the text after it up to the first separator;
/// a bold label ending with `:` → the label alone when it has more than
/// [_shortLabelMaxWords] words, otherwise label plus the text after it up
/// to the first separator (just the label when nothing follows).
({String title, bool truncated}) _titleFrom(String bold, String rest) {
  final b = _cleanTitle(bold);
  if (b.isEmpty) return _capTitle(_firstSegment(rest));
  if (b.endsWith(':')) {
    final label = b.substring(0, b.length - 1).trim();
    if (label.split(' ').length > _shortLabelMaxWords) return _capTitle(label);
    final tail = _firstSegment(rest);
    return _capTitle(tail.isEmpty ? label : '$b $tail');
  }
  return _capTitle(_cleanTitle(_cutAtSeparator(b)));
}

/// Index of the `**` that closes a bold opened right before [from], with
/// nested `**…**` pairs inside it (an inner opener follows whitespace and
/// precedes text); -1 when it is never closed.
int _boldClose(String s, int from) {
  var depth = 1;
  var i = from;
  while (true) {
    final j = s.indexOf('**', i);
    if (j < 0) return -1;
    final before = j > from ? s[j - 1] : '';
    final after = j + 2 < s.length ? s[j + 2] : '';
    final opener =
        j > from && before.trim().isEmpty && after.trim().isNotEmpty;
    depth += opener ? 1 : -1;
    if (depth == 0) return j;
    i = j + 2;
  }
}

/// Parses the hand-written thread lines of a cockpit file. Deterministic:
/// the same text always yields the same titles (the comparison relies on
/// it). U+FE0F (emoji variation selector) is ignored everywhere; lines
/// between the generated markers are skipped.
CockpitParse parseCockpit(String content) {
  final lines = <CockpitLine>[];
  final unparsed = <int>[];
  final skipped = <String, int>{};
  void skip(String reason) => skipped[reason] = (skipped[reason] ?? 0) + 1;
  final headings = <int, String>{};
  var inGenerated = false;
  final rawLines = const LineSplitter().convert(content);
  for (var i = 0; i < rawLines.length; i++) {
    final raw = rawLines[i];
    final line = raw.replaceAll('\u{FE0F}', '').trimRight();
    final trimmed = line.trim();
    if (trimmed == cockpitStartMarker) {
      inGenerated = true;
      continue;
    }
    if (trimmed == cockpitEndMarker) {
      inGenerated = false;
      continue;
    }
    if (inGenerated) {
      skip('generated');
      continue;
    }
    if (trimmed.isEmpty) continue;
    final heading = _heading.firstMatch(line);
    if (heading != null) {
      final level = heading.group(1)!.length;
      headings.removeWhere((l, _) => l >= level);
      headings[level] = heading.group(2)!.trim();
      continue;
    }
    if (line.startsWith(RegExp(r'\s'))) {
      skip('nested');
      continue;
    }
    if (line.startsWith('|')) {
      skip('table');
      continue;
    }
    final body = line.replaceFirst(_listMarker, '');
    if (body.startsWith('~~') || body.startsWith('**~~')) {
      skip('struck');
      continue;
    }
    if (body.startsWith('·')) {
      skip('detail');
      continue;
    }
    if (body.startsWith('⚠') || body.startsWith('**⚠')) {
      skip('warning');
      continue;
    }
    if (_numbered.hasMatch(line)) {
      skip('numbered');
      continue;
    }
    if (_archiveDate.hasMatch(body)) {
      skip('archive');
      continue;
    }
    String? symbol;
    ({String title, bool truncated})? title;
    var struck = false;
    if (body.startsWith('**')) {
      // Bold first: `**▶ Title** …` (nested bold inside is allowed).
      final close = _boldClose(body, 2);
      final inner = close < 0 ? null : body.substring(2, close);
      final m = inner == null
          ? null
          : _symbolAtStart.firstMatch(inner.trimLeft());
      if (m != null) {
        final bold = inner!.trimLeft().substring(m.end);
        symbol = m.group(1);
        struck = bold.trimLeft().startsWith('~~');
        title = _titleFrom(bold, body.substring(close + 2));
      }
    } else {
      final m = _symbolAtStart.firstMatch(body);
      if (m != null) {
        final after = body.substring(m.end);
        final trimmed = after.trimLeft();
        final close = trimmed.startsWith('**')
            ? _boldClose(trimmed, 2)
            : -1;
        if (close > 0) {
          // Symbol first: `▶ **Title** …`.
          final bold = trimmed.substring(2, close);
          symbol = m.group(1);
          struck = bold.trimLeft().startsWith('~~');
          title = _titleFrom(bold, trimmed.substring(close + 2));
        } else if (after.startsWith(RegExp(r'\s')) && trimmed.isNotEmpty) {
          // Plain: `▶ Title – …`.
          symbol = m.group(1);
          title = _capTitle(_firstSegment(trimmed));
        }
      }
    }
    if (struck) {
      skip('struck');
      continue;
    }
    if (symbol == null || title == null || title.title.isEmpty) {
      if (_symbolStart.hasMatch(body)) unparsed.add(i + 1);
      continue;
    }
    lines.add(
      CockpitLine(
        lineNo: i + 1,
        sectionPath: [
          for (final l in headings.keys.toList()..sort()) headings[l]!,
        ],
        symbol: symbol,
        state: _stateBySymbol[symbol]!,
        title: title.title,
        entryRefs: [
          for (final m in _entryRef.allMatches(line)) int.parse(m.group(1)!),
        ],
        titleTruncated: title.truncated,
        raw: raw,
      ),
    );
  }
  return CockpitParse(lines, unparsed, skipped);
}

