String _two(int n) => n.toString().padLeft(2, '0');

/// A stored time as a calendar date for the cockpit: a date-only value
/// (stored as UTC midnight) keeps its own day; any other time is shown as
/// the LOCAL date.
String _date(String? iso) {
  if (iso == null) return 'unknown';
  final u = DateTime.parse(iso).toUtc();
  final d =
      u.hour == 0 && u.minute == 0 && u.second == 0 && u.millisecond == 0
      ? u
      : u.toLocal();
  return '${d.year}-${_two(d.month)}-${_two(d.day)}';
}

/// The generated section (markers included) for [threads] – live rows of
/// [readThreadRows], grouped by project; projects and titles sorted.
/// [now] (local time) only feeds the timestamp line.
String renderThreadSection(
  List<Map<String, Object?>> threads,
  DateTime now,
) {
  final b = StringBuffer()
    ..writeln(cockpitStartMarker)
    ..writeln(
      '$_generatedLinePrefix ${now.year}-${_two(now.month)}-${_two(now.day)} '
      '${_two(now.hour)}:${_two(now.minute)} – do not edit between the '
      'markers; change a state with thread_update._',
    );
  final byProject = <String, List<Map<String, Object?>>>{};
  for (final t in threads) {
    (byProject[t['project'] as String] ??= []).add(t);
  }
  if (byProject.isEmpty) {
    b
      ..writeln()
      ..writeln('_No live threads._');
  }
  for (final project in byProject.keys.toList()..sort()) {
    b
      ..writeln()
      ..writeln('### $project');
    final rows = byProject[project]!
      ..sort((x, y) {
        final byTitle = (x['title'] as String).compareTo(y['title'] as String);
        return byTitle != 0 ? byTitle : (x['id'] as int).compareTo(y['id'] as int);
      });
    for (final t in rows) {
      final state = t['state'] as String;
      final symbol = ThreadStates.symbols[state] ?? '[$state]';
      final parts = <String>[];
      if (state == ThreadStates.paused) {
        parts.add('until ${_date(t['pausedUntil'] as String?)}');
      } else if (t['since'] != null) {
        parts.add('since ${_date(t['since'] as String?)}');
      } else {
        parts.add(
          'since unknown (recorded ${_date(t['sinceRecordedAt'] as String?)})',
        );
      }
      parts.add('thread ${t['id']}');
      final count = t['entryCount'] as int? ?? 0;
      if (count > 0) parts.add('$count ${count == 1 ? 'entry' : 'entries'}');
      if (t['pauseElapsed'] == true) parts.add('pause elapsed');
      b.writeln('- $symbol **${t['title']}** – ${parts.join(' · ')}');
    }
  }
  b.write(cockpitEndMarker);
  return b.toString();
}

/// Result of [replaceThreadSection].
class SectionReplace {
  /// The new file content; null when [error] is set.
  final String? content;

  /// Why the markers were refused.
  final String? error;

  /// The section was appended (no markers yet).
  final bool appended;

  /// The section differs from the current one (timestamp line excluded).
  final bool changed;

  const SectionReplace({
    this.content,
    this.error,
    this.appended = false,
    this.changed = false,
  });
}

String _withoutTimestamp(Iterable<String> lines) => lines
    .where((l) => !l.trimLeft().startsWith(_generatedLinePrefix))
    .map((l) => l.trimRight())
    .join('\n');

/// Puts [section] into [content]: between the existing markers (exactly
/// one start before exactly one end), or appended when both are missing.
/// Any other marker shape is refused ([SectionReplace.error]).
SectionReplace replaceThreadSection(String content, String section) {
  final lines = content.split('\n');
  final starts = <int>[];
  final ends = <int>[];
  for (var i = 0; i < lines.length; i++) {
    final t = lines[i].trim();
    if (t == cockpitStartMarker) starts.add(i);
    if (t == cockpitEndMarker) ends.add(i);
  }
  if (starts.isEmpty && ends.isEmpty) {
    final base = content.isEmpty || content.endsWith('\n')
        ? content
        : '$content\n';
    return SectionReplace(
      content: '$base\n$section\n',
      appended: true,
      changed: true,
    );
  }
  if (starts.length != 1 || ends.length != 1 || starts.single > ends.single) {
    return SectionReplace(
      error:
          'expected exactly one "$cockpitStartMarker" line before exactly '
          'one "$cockpitEndMarker" line, found ${starts.length} start '
          '(lines ${starts.map((i) => i + 1).join(', ')}) and ${ends.length} '
          'end (lines ${ends.map((i) => i + 1).join(', ')}) marker(s)',
    );
  }
  final old = lines.sublist(starts.single, ends.single + 1);
  final next = section.split('\n');
  final changed = _withoutTimestamp(old) != _withoutTimestamp(next);
  return SectionReplace(
    content: [
      ...lines.sublist(0, starts.single),
      ...next,
      ...lines.sublist(ends.single + 1),
    ].join('\n'),
    changed: changed,
  );
}

