const String _usage =
    'usage: remembox cockpit-sync [--cockpit <path>] [--dry-run] '
    '[--parse-only]\n'
    '  --cockpit <path>  the cockpit file (default: OBX_MEMORY_COCKPIT_FILE)\n'
    '  --dry-run         read, render and compare; write nothing\n'
    '  --parse-only      print the parsed hand lines as JSON on stdout (no '
    'store access)';

/// Runs `remembox cockpit-sync` with [args] (everything after the
/// subcommand) and returns the exit code ([CockpitExit]). [env] defaults to
/// the process environment; [out] (stdout) only receives the
/// `--parse-only` JSON. Relative paths (`--cockpit`,
/// `OBX_MEMORY_COCKPIT_FILE`, `OBX_MEMORY_COCKPIT_LOG`) are resolved
/// against `REMEMBOX_CALLER_CWD` – the directory the launcher was started
/// from (it changes into `dist/` itself) – or the current directory.
/// [debugBeforeWrite] is a test seam: it runs right before the
/// changed-during-sync re-check, after the backup. The cockpit is read as
/// LF text (CRLF files are not supported).
Future<int> runCockpitSync(
  List<String> args, {
  LogSink log = stderrLog,
  Map<String, String>? env,
  IOSink? out,
  @visibleForTesting void Function()? debugBeforeWrite,
}) async {
  final e = env ?? Platform.environment;
  String? cockpitArg;
  var dryRun = false;
  var parseOnly = false;
  for (var i = 0; i < args.length; i++) {
    final a = args[i];
    if (a == '--dry-run') {
      dryRun = true;
    } else if (a == '--parse-only') {
      parseOnly = true;
    } else if (a == '--cockpit' && i + 1 < args.length) {
      cockpitArg = args[++i];
    } else if (a.startsWith('--cockpit=')) {
      cockpitArg = a.substring('--cockpit='.length);
    } else if (a == '--help' || a == '-h') {
      log(_usage);
      return CockpitExit.ok;
    } else {
      log('[cockpit] unknown argument "${sanitizeForLog(a)}"\n$_usage');
      return CockpitExit.usage;
    }
  }
  final callerCwd = (e['REMEMBOX_CALLER_CWD'] ?? '').isNotEmpty
      ? e['REMEMBOX_CALLER_CWD']!
      : Directory.current.path;
  String resolve(String path) =>
      p.isAbsolute(path) ? path : p.normalize(p.join(callerCwd, path));
  final rawCockpit = cockpitArg ?? e['OBX_MEMORY_COCKPIT_FILE'] ?? '';
  if (rawCockpit.isEmpty) {
    log(
      '[cockpit] no cockpit file: pass --cockpit <path> or set '
      'OBX_MEMORY_COCKPIT_FILE\n$_usage',
    );
    return CockpitExit.usage;
  }
  final cockpitPath = resolve(rawCockpit);
  final compareLog = resolve(cockpitCompareLogPath(e));
  // A dry run writes nothing at all – not even a failure line.
  void fail(String msg, {Map<String, Object?> extra = const {}}) {
    log('[cockpit] $msg');
    if (!dryRun) _logFailure(compareLog, cockpitPath, msg, log, extra: extra);
  }

  final cockpit = File(cockpitPath);
  if (!cockpit.existsSync()) {
    log('[cockpit] the cockpit file does not exist: $cockpitPath');
    return CockpitExit.error;
  }

  final List<int> readBytes;
  final String content;
  final String readHash;
  final DateTime readModified;
  try {
    readBytes = cockpit.readAsBytesSync();
    readHash = sha256.convert(readBytes).toString();
    readModified = cockpit.statSync().modified;
    content = utf8.decode(readBytes);
  } on FileSystemException catch (err) {
    log('[cockpit] could not read $cockpitPath: $err');
    return CockpitExit.error;
  } on FormatException catch (err) {
    log('[cockpit] $cockpitPath is not UTF-8: ${err.message}');
    return CockpitExit.error;
  }

  final parsed = parseCockpit(content);
  if (parsed.unparsed.isNotEmpty) {
    log(
      '[cockpit] ${parsed.unparsed.length} line(s) start with a state symbol '
      'but match no thread-line pattern: lines '
      '${parsed.unparsed.join(', ')}',
    );
  }
  if (parseOnly) {
    final sink = out ?? stdout;
    sink.writeln(jsonEncode(parsed.toJson()));
    await sink.flush();
    log(
      '[cockpit] parse-only: parsed=${parsed.lines.length} '
      'unparsed=${parsed.unparsed.length} skipped=${jsonEncode(parsed.skipped)}',
    );
    return CockpitExit.ok;
  }

  // -- Read the threads: one gated lending ---------------------------------
  final String storeDir;
  try {
    storeDir = MemoryConfig.fromEnvironment(env: e).storeDir;
  } on ArgumentError catch (err) {
    log('[cockpit] configuration error: ${err.message}');
    return CockpitExit.error;
  }
  if (!File(p.join(storeDir, 'data.mdb')).existsSync()) {
    // Never create a store here: an empty one would render "no threads"
    // over the real section.
    fail(
      'no RememBox store at $storeDir (data.mdb missing) – check '
      'OBX_MEMORY_DIR',
    );
    return CockpitExit.error;
  }
  final ({
    List<Map<String, Object?>> threads,
    int total,
    bool truncated,
  }) live;
  final ({
    List<Map<String, Object?>> threads,
    int total,
    bool truncated,
  }) all;
  try {
    final gate = await StoreGate.gated(storeDirectory: storeDir, log: log);
    try {
      (live, all) = await gate.withStore(
        'cockpit-sync',
        (session) => (
          readThreadRows(session),
          readThreadRows(session, includeClosed: true),
        ),
      );
    } finally {
      await gate.close();
    }
  } catch (err) {
    // Anything – e.g. a persistent-mode process (--serve or
    // OBX_MEMORY_SYNC_URL) holding store.lock (the startup probe gives up
    // after 8 s), or a store that cannot be opened: logged, never a raw
    // crash.
    fail(
      'could not read the store at $storeDir: '
      '${sanitizeForLog(err is StateError ? err.message : '$err')}',
    );
    return CockpitExit.error;
  }
  if (live.truncated) {
    fail(
      'cockpit not written: ${live.total} live threads, only the first '
      '${live.threads.length} could be read – the section would be '
      'incomplete',
      extra: {'truncated': true},
    );
    return CockpitExit.error;
  }
  if (all.truncated) {
    log(
      '[cockpit] WARN: ${all.total} threads (closed included), only the '
      'first ${all.threads.length} read – the comparison is incomplete',
    );
  }

  final section = renderThreadSection(live.threads, DateTime.now());
  final replaced = replaceThreadSection(content, section);
  if (replaced.error != null) {
    fail('cockpit not written: ${replaced.error}');
    return CockpitExit.badMarkers;
  }
  final compare = compareCockpit(parsed.lines, all.threads);
  for (final m in compare.mismatches) {
    log(
      '[cockpit] mismatch line ${m['lineNo']} "${sanitizeForLog('${m['title']}')}": '
      'line says ${m['lineState']}, thread ${m['threadId']} is '
      '${m['threadState']}',
    );
  }
  for (final m in compare.noThread) {
    log(
      '[cockpit] no thread for line ${m['lineNo']} '
      '"${sanitizeForLog('${m['title']}')}"',
    );
  }
  for (final m in compare.noLine) {
    log(
      '[cockpit] no hand line for thread ${m['threadId']} '
      '"${sanitizeForLog('${m['title']}')}"',
    );
  }
  for (final m in compare.ambiguous) {
    log(
      '[cockpit] ambiguous line ${m['lineNo']} '
      '"${sanitizeForLog('${m['title']}')}": threads ${m['threadIds']}',
    );
  }
  final summary =
      'parsed=${parsed.lines.length} unparsed=${parsed.unparsed.length} '
      'threads=${live.threads.length} sectionChanged=${replaced.changed} '
      'mismatches=${compare.mismatches.length} '
      'noThread=${compare.noThread.length} noLine=${compare.noLine.length} '
      'ambiguous=${compare.ambiguous.length}';
  if (dryRun) {
    log('[cockpit] dry run (nothing written): $summary');
    return CockpitExit.ok;
  }

  // -- Write the cockpit, in place, only if unchanged since the read --------
  if (replaced.changed) {
    // The backup lives next to the compare log, NEVER next to the cockpit
    // (a second cockpit-like file there is exactly what the operator rule
    // forbids). Mode 600: it is the cockpit's content.
    final backup = File(p.join(p.dirname(compareLog), 'cockpit.bak'));
    try {
      backup.parent.createSync(recursive: true);
      backup.writeAsBytesSync(readBytes);
      tightenPermissions(backup.path, '600', log: log);
    } on FileSystemException catch (err) {
      fail('could not write the backup ${backup.path}: $err – nothing written');
      return CockpitExit.error;
    }
    debugBeforeWrite?.call();
    try {
      // The re-check sits immediately before the write.
      final nowBytes = cockpit.readAsBytesSync();
      final nowModified = cockpit.statSync().modified;
      if (sha256.convert(nowBytes).toString() != readHash ||
          nowModified != readModified) {
        fail('cockpit changed during sync – retry; nothing written');
        return CockpitExit.changedDuringSync;
      }
      // FileMode.write truncates and rewrites the SAME file (inode), so
      // its mode and extended attributes stay – no temp file + rename.
      cockpit.writeAsStringSync(replaced.content!, mode: FileMode.write);
    } on FileSystemException catch (err) {
      fail('could not write the cockpit: $err');
      return CockpitExit.error;
    }
    if (replaced.appended) {
      log(
        '[cockpit] the markers were missing – the generated section was '
        'appended at the end of $cockpitPath; move the marker pair once to '
        'where it belongs, later runs replace it in place',
      );
    }
  }

  // -- The compare log, deduplicated by hash --------------------------------
  final hash = compare.hash;
  var logState = 'unchanged';
  try {
    if (_lastLoggedHash(File(compareLog), log) != hash) {
      _appendCompareLog(compareLog, {
        'at': DateTime.now().toUtc().toIso8601String(),
        'cockpit': cockpitPath,
        'sectionChanged': replaced.changed,
        'parsed': parsed.lines.length,
        'unparsed': parsed.unparsed.length,
        'skipped': parsed.skipped,
        if (all.truncated) 'truncated': true,
        'mismatches': compare.mismatches,
        'noThread': compare.noThread,
        'noLine': compare.noLine,
        'ambiguous': compare.ambiguous,
        'hash': hash,
      }, log);
      logState = 'appended';
    }
  } on FileSystemException catch (err) {
    log('[cockpit] could not write the compare log $compareLog: $err');
    return CockpitExit.error;
  }
  log('[cockpit] $summary log=$logState');
  return CockpitExit.ok;
}
