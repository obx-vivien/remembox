/// Hand lines vs threads, matched by [ScopeKey] of the title across all
/// projects. A key with several threads uses the single live one if there
/// is exactly one, otherwise it is `ambiguous`.
class CockpitCompare {
  final List<Map<String, Object?>> mismatches;
  final List<Map<String, Object?>> noThread;
  final List<Map<String, Object?>> noLine;
  final List<Map<String, Object?>> ambiguous;

  const CockpitCompare(
    this.mismatches,
    this.noThread,
    this.noLine,
    this.ambiguous,
  );

  /// sha256 over the four sets without line numbers (amendment A8: a line
  /// moving up or down is not a new finding).
  String get hash {
    List<String> canonical(List<Map<String, Object?>> rows) =>
        [
          for (final r in rows)
            jsonEncode({
              for (final k in (r.keys.toList()..sort()))
                if (k != 'lineNo') k: r[k],
            }),
        ]..sort();
    return sha256
        .convert(
          utf8.encode(
            jsonEncode({
              'mismatches': canonical(mismatches),
              'noThread': canonical(noThread),
              'noLine': canonical(noLine),
              'ambiguous': canonical(ambiguous),
            }),
          ),
        )
        .toString();
  }
}

CockpitCompare compareCockpit(
  List<CockpitLine> lines,
  List<Map<String, Object?>> threads,
) {
  final byKey = <String, List<Map<String, Object?>>>{};
  for (final t in threads) {
    (byKey[ScopeKey.of(t['title'] as String)] ??= []).add(t);
  }
  final mismatches = <Map<String, Object?>>[];
  final noThread = <Map<String, Object?>>[];
  final ambiguous = <Map<String, Object?>>[];
  final lineKeys = <String>{};
  for (final line in lines) {
    final key = line.titleKey;
    lineKeys.add(key);
    final candidates = byKey[key] ?? const [];
    if (candidates.isEmpty) {
      noThread.add({
        'lineNo': line.lineNo,
        'title': line.title,
        'lineState': line.state,
      });
      continue;
    }
    final live = candidates.where((t) => t['closed'] != true).toList();
    final pick = live.length == 1
        ? live.single
        : (live.isEmpty && candidates.length == 1 ? candidates.single : null);
    if (pick == null) {
      ambiguous.add({
        'lineNo': line.lineNo,
        'title': line.title,
        'threadIds': [for (final t in candidates) t['id']],
      });
      continue;
    }
    if (pick['state'] != line.state) {
      mismatches.add({
        'lineNo': line.lineNo,
        'title': line.title,
        'lineState': line.state,
        'threadId': pick['id'],
        'threadState': pick['state'],
        'since': pick['since'],
      });
    }
  }
  final noLine = [
    for (final t in threads)
      if (t['closed'] != true &&
          !lineKeys.contains(ScopeKey.of(t['title'] as String)))
        {
          'threadId': t['id'],
          'title': t['title'],
          'project': t['project'],
          'state': t['state'],
        },
  ];
  return CockpitCompare(mismatches, noThread, noLine, ambiguous);
}

